-- 스키마는 postgres 초기화 SQL이 만들지만 compose 밖에서 단독으로 띄울 때도 돌도록 한 번 더 확인한다.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(40)  NOT NULL UNIQUE,
    password_hash varchar(100) NOT NULL,
    name          varchar(40)  NOT NULL,
    role          varchar(30)  NOT NULL,
    dept          varchar(30)  NOT NULL,
    title         varchar(60)  NOT NULL,
    phone         varchar(20)
);

CREATE TABLE IF NOT EXISTS projects (
    id                     bigint PRIMARY KEY,
    name                   varchar(100) NOT NULL,
    block_budget_cap       bigint       NOT NULL,
    crew_weekly_hours_used numeric(5, 1) NOT NULL
);

CREATE TABLE IF NOT EXISTS shoot_days (
    id           bigint PRIMARY KEY,
    project_id   bigint  NOT NULL REFERENCES projects (id),
    shoot_date   date    NOT NULL,
    call_time    time    NOT NULL,
    data_version integer NOT NULL,
    notice       text,
    crew_calls   jsonb   NOT NULL DEFAULT '[]'
);

CREATE TABLE IF NOT EXISTS actors (
    id                bigint PRIMARY KEY,
    name              varchar(40)   NOT NULL,
    available_from    time          NOT NULL,
    available_to      time          NOT NULL,
    weekly_hours_used numeric(5, 1) NOT NULL,
    contract_doc_id   varchar(60)   NOT NULL,
    no_night          boolean       NOT NULL,
    max_daily_hours   numeric(4, 1),
    manager_phone     varchar(20)
);

CREATE TABLE IF NOT EXISTS locations (
    id          bigint PRIMARY KEY,
    name        varchar(60)   NOT NULL,
    address     varchar(120)  NOT NULL,
    indoor      boolean       NOT NULL,
    region      varchar(40)   NOT NULL,
    open_from   time          NOT NULL,
    open_to     time          NOT NULL,
    permit_from time,
    permit_to   time,
    cost        bigint        NOT NULL,
    no_fly_zone boolean       NOT NULL,
    fit         numeric(4, 2) NOT NULL,
    distance_km numeric(6, 1) NOT NULL,
    note        text
);

CREATE TABLE IF NOT EXISTS equipment (
    id        bigint PRIMARY KEY,
    name      varchar(60) NOT NULL,
    available boolean     NOT NULL,
    drone     boolean     NOT NULL,
    cost      bigint      NOT NULL
);

CREATE TABLE IF NOT EXISTS blocks (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shoot_day_id  bigint      NOT NULL REFERENCES shoot_days (id),
    code          varchar(10) NOT NULL,
    start_time    time        NOT NULL,
    end_time      time        NOT NULL,
    duration_min  integer     NOT NULL,
    location_id   bigint REFERENCES locations (id),
    equipment_ids jsonb       NOT NULL DEFAULT '[]',
    UNIQUE (shoot_day_id, code)
);

CREATE TABLE IF NOT EXISTS scenes (
    code           varchar(10) PRIMARY KEY,
    shoot_day_id   bigint REFERENCES shoot_days (id),
    block_code     varchar(10),
    title          varchar(80) NOT NULL,
    duration_min   integer     NOT NULL,
    outdoor_intent boolean     NOT NULL,
    location_id    bigint REFERENCES locations (id),
    actor_ids      jsonb       NOT NULL DEFAULT '[]',
    sort           integer     NOT NULL
);

CREATE TABLE IF NOT EXISTS plan_options (
    shoot_day_id  bigint        NOT NULL REFERENCES shoot_days (id),
    block_code    varchar(10)   NOT NULL,
    option_no     integer       NOT NULL,
    location_id   bigint        NOT NULL REFERENCES locations (id),
    equipment_ids jsonb         NOT NULL,
    equipment_fit numeric(4, 2) NOT NULL,
    start_time    time          NOT NULL,
    end_time      time          NOT NULL,
    PRIMARY KEY (shoot_day_id, block_code, option_no)
);

-- 콜시트 버전은 바뀌는 오후 블록만 스냅숏으로 남기고 나머지는 조회할 때 고정 블록에서 채운다.
CREATE TABLE IF NOT EXISTS callsheet_versions (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shoot_day_id     bigint      NOT NULL REFERENCES shoot_days (id),
    version_no       integer     NOT NULL,
    proposal_id      bigint,
    pm_location_id   bigint      NOT NULL REFERENCES locations (id),
    pm_equipment_ids jsonb       NOT NULL,
    pm_start         time        NOT NULL,
    pm_end           time        NOT NULL,
    pm_cost          bigint      NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (shoot_day_id, version_no)
);

CREATE TABLE IF NOT EXISTS weather_forecasts (
    shoot_day_id bigint  NOT NULL REFERENCES shoot_days (id),
    location_id  bigint  NOT NULL REFERENCES locations (id),
    hour         integer NOT NULL,
    precip_prob  integer NOT NULL,
    PRIMARY KEY (shoot_day_id, location_id, hour)
);

CREATE TABLE IF NOT EXISTS disaster_alerts (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region     varchar(40) NOT NULL,
    kind       varchar(40) NOT NULL,
    starts_at  time        NOT NULL,
    ends_at    time        NOT NULL,
    message    text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reservations (
    id           varchar(20) PRIMARY KEY,
    shoot_day_id bigint      NOT NULL REFERENCES shoot_days (id),
    location_id  bigint      NOT NULL REFERENCES locations (id),
    start_time   time        NOT NULL,
    end_time     time        NOT NULL,
    status       varchar(20) NOT NULL,
    provider     varchar(20) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS external_locations (
    id          bigint PRIMARY KEY,
    name        varchar(60)   NOT NULL,
    indoor      boolean       NOT NULL,
    region      varchar(40)   NOT NULL,
    distance_km numeric(6, 1) NOT NULL,
    cost        bigint        NOT NULL,
    keywords    jsonb         NOT NULL
);

CREATE TABLE IF NOT EXISTS ontology_nodes (
    node_id varchar(80) PRIMARY KEY,
    type    varchar(30) NOT NULL,
    label   varchar(80) NOT NULL,
    props   jsonb       NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS ontology_edges (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    src        varchar(80) NOT NULL REFERENCES ontology_nodes (node_id),
    relation   varchar(30) NOT NULL,
    dst        varchar(80) NOT NULL REFERENCES ontology_nodes (node_id),
    created_by varchar(40) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (src, relation, dst)
);

CREATE TABLE IF NOT EXISTS change_events (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shoot_day_id bigint       NOT NULL REFERENCES shoot_days (id),
    type         varchar(30)  NOT NULL,
    detail       text         NOT NULL,
    instruction  text,
    data_version integer      NOT NULL,
    dedup_key    varchar(600) NOT NULL UNIQUE,
    requested_by varchar(40)  NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ai_tasks (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         varchar(10)  NOT NULL,
    status       varchar(20)  NOT NULL,
    question     text,
    answer       text,
    sources      jsonb,
    event_id     bigint,
    proposal_id  bigint,
    trace_url    text,
    thread_id    varchar(60),
    trace_id     varchar(40)  NOT NULL,
    shoot_day_id bigint       NOT NULL,
    requested_by varchar(40)  NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ai_task_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    bigint      NOT NULL REFERENCES ai_tasks (id) ON DELETE CASCADE,
    type       varchar(30) NOT NULL,
    payload    jsonb       NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ai_task_events_task_idx ON ai_task_events (task_id, id);

CREATE TABLE IF NOT EXISTS proposals (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id            bigint           NOT NULL,
    event_id           bigint,
    shoot_day_id       bigint           NOT NULL REFERENCES shoot_days (id),
    loop_no            integer          NOT NULL,
    version_no         integer          NOT NULL,
    status             varchar(20)      NOT NULL,
    data_version       integer          NOT NULL,
    orig_location_id   bigint           NOT NULL,
    orig_equipment_ids jsonb            NOT NULL,
    orig_start         time             NOT NULL,
    orig_end           time             NOT NULL,
    orig_cost          bigint           NOT NULL,
    location_id        bigint           NOT NULL,
    equipment_ids      jsonb            NOT NULL,
    start_time         time             NOT NULL,
    end_time           time             NOT NULL,
    cost               bigint           NOT NULL,
    source             jsonb            NOT NULL,
    score              double precision NOT NULL,
    score_breakdown    jsonb            NOT NULL,
    weights            jsonb            NOT NULL,
    explanation        text,
    checklist          jsonb            NOT NULL,
    evidence           jsonb            NOT NULL,
    unresolved         jsonb            NOT NULL,
    created_at         timestamptz      NOT NULL DEFAULT now(),
    updated_at         timestamptz      NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS approvals (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id bigint      NOT NULL REFERENCES proposals (id) ON DELETE CASCADE,
    seq         integer     NOT NULL,
    role        varchar(30) NOT NULL,
    status      varchar(20) NOT NULL,
    user_name   varchar(40),
    reason      text,
    decided_at  timestamptz,
    UNIQUE (proposal_id, role)
);

CREATE TABLE IF NOT EXISTS notifications (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint       NOT NULL REFERENCES users (id),
    kind       varchar(20)  NOT NULL,
    title      varchar(200) NOT NULL,
    body       text,
    link       varchar(200),
    read       boolean      NOT NULL DEFAULT false,
    created_at timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notifications_user_idx ON notifications (user_id, id);

CREATE TABLE IF NOT EXISTS outbox (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key varchar(60) NOT NULL,
    payload     jsonb       NOT NULL,
    status      varchar(10) NOT NULL,
    attempts    integer     NOT NULL DEFAULT 0,
    last_error  text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    sent_at     timestamptz
);
-- 릴레이는 1초마다 NEW만 찾으므로 SENT가 쌓여도 느려지지 않게 부분 인덱스를 둔다.
CREATE INDEX IF NOT EXISTS outbox_new_idx ON outbox (id) WHERE status = 'NEW';

CREATE TABLE IF NOT EXISTS job_logs (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue      varchar(60) NOT NULL,
    message_id varchar(80),
    attempt    integer     NOT NULL,
    status     varchar(10) NOT NULL,
    error      text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS distribution_logs (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    callsheet_version_id bigint      NOT NULL,
    user_id              bigint      NOT NULL REFERENCES users (id),
    channel              varchar(10) NOT NULL,
    status               varchar(10) NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    UNIQUE (callsheet_version_id, user_id, channel)
);

-- 거절할 때 문제로 고른 요소(LOCATION, TIME, EQUIPMENT, COST, OTHER)다. Agent가 이 요소만 바꿔 다시 계획한다.
ALTER TABLE approvals ADD COLUMN IF NOT EXISTS issues jsonb NOT NULL DEFAULT '[]';

-- 1/2/3안이 모두 막혔을 때 Agent가 아워플레이스 카탈로그에서 골라 등록한 4안 장소다.
CREATE TABLE IF NOT EXISTS shoot_day_alternatives (
    shoot_day_id bigint      NOT NULL REFERENCES shoot_days (id),
    location_id  bigint      NOT NULL REFERENCES locations (id),
    external_id  bigint      NOT NULL REFERENCES external_locations (id),
    keywords     jsonb       NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (shoot_day_id, location_id)
);

-- 승인 요청 전에 Agent가 매긴 자체 검토 점수와 회차별 이력이다.
ALTER TABLE proposals ADD COLUMN IF NOT EXISTS review jsonb;

-- 관리자 표시와 탈퇴(비활성) 상태다. 탈퇴한 계정은 로그인과 연락처, 알림 대상에서 빠진다.
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS active boolean NOT NULL DEFAULT true;

-- 강수확률 대신 시간당 강수량(mm)으로 판정한다. 확률 열은 예전 데이터 호환을 위해 남겨 둔다.
ALTER TABLE weather_forecasts ADD COLUMN IF NOT EXISTS precip_mm numeric(5, 1) NOT NULL DEFAULT 0;

-- 관리자가 바꾸는 운영 설정이다. 행은 하나만 둔다.
CREATE TABLE IF NOT EXISTS app_settings (
    id                    integer      PRIMARY KEY CHECK (id = 1),
    max_loops             integer      NOT NULL,
    rain_block_mm         numeric(4, 1) NOT NULL,
    rain_warn_mm          numeric(4, 1) NOT NULL,
    rain_alert_lead_hours integer      NOT NULL,
    updated_by            varchar(40),
    updated_at            timestamptz  NOT NULL DEFAULT now()
);

-- 변경 내용별 필수 승인자다. change_kind는 ALWAYS, LOCATION, EQUIPMENT, TIME, COST 중 하나다.
CREATE TABLE IF NOT EXISTS approver_rules (
    change_kind varchar(20) NOT NULL,
    role        varchar(30) NOT NULL,
    PRIMARY KEY (change_kind, role)
);

-- 변경 입력에서 고른 구조화된 변경(장비 고장, 배우 가용 시간, 장소 취소, 강수량)이다.
-- 원본 시드 행을 고치지 않고 덮어쓰기로 남겨서, 엔진과 촬영판이 읽을 때 반영하고 초기화 때 지우기만 하면 되게 한다.
CREATE TABLE IF NOT EXISTS shoot_day_overrides (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shoot_day_id bigint      NOT NULL REFERENCES shoot_days (id),
    event_id     bigint,
    kind         varchar(30) NOT NULL,
    target_id    bigint,
    payload      jsonb       NOT NULL DEFAULT '{}',
    created_at   timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE change_events ADD COLUMN IF NOT EXISTS changes jsonb NOT NULL DEFAULT '[]';

-- 자원 현황 패널에서 고친 상태의 적용 기간, 사유, 되돌리기 기록이다.
-- until_date가 있으면 starts_on부터 그날까지 모든 촬영일에 적용하고, 없으면 등록한 촬영일에만 적용한다.
-- 되돌린 행은 지우지 않고 cleared_at을 채워 이력으로 남긴다.
ALTER TABLE shoot_day_overrides ADD COLUMN IF NOT EXISTS starts_on date;
ALTER TABLE shoot_day_overrides ADD COLUMN IF NOT EXISTS until_date date;
ALTER TABLE shoot_day_overrides ADD COLUMN IF NOT EXISTS memo text;
ALTER TABLE shoot_day_overrides ADD COLUMN IF NOT EXISTS created_by varchar(40);
ALTER TABLE shoot_day_overrides ADD COLUMN IF NOT EXISTS cleared_at timestamptz;
ALTER TABLE shoot_day_overrides ADD COLUMN IF NOT EXISTS cleared_by varchar(40);

-- 우천 촬영 불가 알림을 같은 장소와 시각에 두 번 보내지 않으려고 보낸 기록을 남긴다.
CREATE TABLE IF NOT EXISTS rain_alerts_sent (
    shoot_day_id bigint      NOT NULL,
    location_id  bigint      NOT NULL,
    hour         integer     NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (shoot_day_id, location_id, hour)
);
